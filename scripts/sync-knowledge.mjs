#!/usr/bin/env node
/**
 * Syncs the business knowledge from the private brain repo
 * (nicxes/os.sportcarslux.com) into a generated TypeScript module,
 * so it gets bundled into the build (no fs reads at runtime — Vercel
 * deployments don't ship src/ files).
 *
 * Sources, in order of preference:
 *   1. GitHub clone using KNOWLEDGE_REPO_TOKEN or GITHUB_TOKEN (Vercel build)
 *   2. Local checkout at ../os.sportcarslux.com (local dev)
 *   3. None found → generates an empty module and warns (build still succeeds)
 *
 * IMPORTANT: this repo is PUBLIC and the brain repo is PRIVATE.
 * The generated module (src/lib/knowledge-data.ts) is gitignored and must
 * never be committed.
 */
import { execSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = path.join(ROOT, "src/lib/knowledge-data.ts");
const REPO = "github.com/nicxes/os.sportcarslux.com";
const LOCAL_CHECKOUT = path.resolve(ROOT, "../os.sportcarslux.com");

function resolveSource() {
  const token = process.env.KNOWLEDGE_REPO_TOKEN || process.env.GITHUB_TOKEN;
  if (token) {
    const dir = mkdtempSync(path.join(tmpdir(), "brain-"));
    execSync(`git clone --depth 1 https://x-access-token:${token}@${REPO} ${dir}`, {
      stdio: ["ignore", "ignore", "inherit"],
    });
    return { dir, cleanup: () => rmSync(dir, { recursive: true, force: true }) };
  }
  if (existsSync(path.join(LOCAL_CHECKOUT, "AGENTS.md"))) {
    return { dir: LOCAL_CHECKOUT, cleanup: () => {} };
  }
  return null;
}

function collectMarkdown(dir, prefix = "") {
  const files = {};
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".") || entry === "node_modules") continue;
    const full = path.join(dir, entry);
    const rel = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(full).isDirectory()) {
      Object.assign(files, collectMarkdown(full, rel));
    } else if (entry.endsWith(".md")) {
      files[rel] = readFileSync(full, "utf8");
    }
  }
  return files;
}

function main() {
  const source = resolveSource();
  let files = {};
  let version = "none";

  if (source) {
    // AGENTS.md + knowledge/** are the brain; skills ship as playbooks/**
    const agents = path.join(source.dir, "AGENTS.md");
    if (existsSync(agents)) files["AGENTS.md"] = readFileSync(agents, "utf8");
    const knowledge = path.join(source.dir, "knowledge");
    if (existsSync(knowledge)) {
      const collected = collectMarkdown(knowledge, "knowledge");
      Object.assign(files, collected);
    }
    const skills = path.join(source.dir, ".claude/skills");
    if (existsSync(skills)) {
      for (const skill of readdirSync(skills)) {
        const skillFile = path.join(skills, skill, "SKILL.md");
        if (existsSync(skillFile)) files[`playbooks/${skill}.md`] = readFileSync(skillFile, "utf8");
      }
    }
    try {
      version = execSync("git rev-parse --short HEAD", { cwd: source.dir }).toString().trim();
    } catch {
      version = "unknown";
    }
    source.cleanup();
  } else {
    console.warn(
      "[sync-knowledge] WARNING: no knowledge source found (no KNOWLEDGE_REPO_TOKEN and no local ../os.sportcarslux.com). Building with empty knowledge."
    );
  }

  const banner =
    "// GENERATED by scripts/sync-knowledge.mjs — DO NOT EDIT, DO NOT COMMIT.\n" +
    "// Contains private business knowledge bundled at build time.\n";
  writeFileSync(
    OUT_FILE,
    banner +
      `export const KNOWLEDGE_VERSION = ${JSON.stringify(version)};\n` +
      `export const KNOWLEDGE_SYNCED_AT = ${JSON.stringify(new Date().toISOString())};\n` +
      `export const KNOWLEDGE: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
  );
  console.log(`[sync-knowledge] bundled ${Object.keys(files).length} files (brain @ ${version})`);
}

main();
